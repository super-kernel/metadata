<?php

declare(strict_types=1);

namespace SuperKernel\Metadata\Provider;

use SuperKernel\Attribute\FactoryProvider;
use SuperKernel\Contract\BasePathInterface;
use SuperKernel\Contract\PackageManagerInterface;
use SuperKernel\Contract\VendorDirInterface;
use SuperKernel\Metadata\Build\LockHash;
use SuperKernel\Metadata\Exception\BuildRequiredException;
use SuperKernel\Metadata\Storage\BuildStampStorage;
use SuperKernel\Metadata\Storage\PackageRecordStorage;

use function hash_equals;
use function sprintf;

#[FactoryProvider(PackageManagerInterface::class)]
final readonly class PackageManagerProvider
{
    /**
     * Restores the package manager from the generated records without reading Composer files or scanning sources.
     *
     * The build stamp must match this package's protocol and the project's current `composer.lock`.
     *
     * @return PackageManagerInterface A fresh manager over the restored packages and class maps
     *
     * @throws BuildRequiredException When the stamp or records are missing, invalid, or out of date
     */
    public function __invoke(VendorDirInterface $vendorDir, BasePathInterface $basePath): PackageManagerInterface
    {
        $stamp = new BuildStampStorage($vendorDir)->read();
        $lock = LockHash::of($basePath)
            ?? throw new BuildRequiredException(sprintf('The project %s has no readable composer.lock.', $basePath));

        if (!hash_equals($stamp->lock(), $lock)) {
            throw new BuildRequiredException(sprintf(
                'The metadata generated by SKERNEL %s does not match the current composer.lock.',
                $stamp->skernel(),
            ));
        }

        return new PackageRecordStorage($vendorDir)->read($basePath);
    }
}
