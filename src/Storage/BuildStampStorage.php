<?php

declare(strict_types=1);

namespace SuperKernel\Metadata\Storage;

use SuperKernel\Contract\VendorDirInterface;
use SuperKernel\Metadata\Constants\ArtifactLayout;
use SuperKernel\Metadata\Constants\Protocol;
use SuperKernel\Metadata\Exception\BuildRequiredException;
use SuperKernel\Metadata\Exception\MetadataException;
use SuperKernel\Metadata\Model\BuildStamp;
use Throwable;

use function sprintf;

/**
 * Reads the build stamp of the current protocol, and writes or removes it.
 *
 * @internal
 */
final readonly class BuildStampStorage
{
    private ArtifactFile $file;

    public function __construct(VendorDirInterface $vendorDir)
    {
        $this->file = new ArtifactFile($vendorDir, ArtifactLayout::BuildStamp);
    }

    /**
     * @throws BuildRequiredException When the stamp is missing, invalid, or written under another protocol
     */
    public function read(): BuildStamp
    {
        $contents = $this->file->read()
            ?? throw new BuildRequiredException(sprintf('The build stamp %s is missing.', $this->file->path()));
        $stamp = BuildStamp::decode($contents);

        if (Protocol::VERSION !== $stamp->protocol()) {
            throw new BuildRequiredException(sprintf(
                'The metadata was generated by SKERNEL %s under build protocol %d, but this project expects %d.',
                $stamp->skernel(),
                $stamp->protocol(),
                Protocol::VERSION,
            ));
        }

        return $stamp;
    }

    /**
     * @throws MetadataException When the stamp cannot be encoded or published
     */
    public function write(BuildStamp $stamp): void
    {
        try {
            $contents = $stamp->encode();
        } catch (Throwable $exception) {
            throw new MetadataException('Unable to encode the build stamp.', 0, $exception);
        }

        $this->file->write($contents);
    }

    /**
     * @throws MetadataException When an existing stamp cannot be removed
     */
    public function delete(): void
    {
        $this->file->delete();
    }
}
